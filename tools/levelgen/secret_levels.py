"""Секретные уровни — по одному на эпизод.

В каждый ведёт секретный слипгейт Z, спрятанный за тайной стеной обычного уровня
(поле secretNext), а выход секретного уровня возвращает в эпизод — на уровень,
следующий за тем, где нашли тайник. У каждого своя особенность:

    E1M7 «Головокружение»     — тяжесть вдвое меньше: зиккурат над лавовым морем
    E2M7 «Кровавая баня»      — только топор, зато четверной урон по пути
    E3M7 «Арена Нижнего мира» — пять волн монстров, выход — после последней
    E4M7 «Тёмная сторона»     — почти без света, у героя фонарь
"""
from ldtools import floor_secret, wall_secret


# ---------------------------------------------------------------- E1M7
def e1m7(M, level):
    m = M(150, 60)
    # небо и лавовое море под ним
    m.fill(1, 1, 148, 52, ',')
    m.fill(1, 53, 148, 58, '!')
    # стартовый утёс с погребом
    m.fill(1, 44, 13, 58, '#')
    m.put(4, 43, 'P')
    m.put(7, 43, 'L')
    floor_secret(m, 9, 44, 'HU')
    # парящие плиты к подножию зиккурата
    for (x0, x1, top) in ((20, 25, 42), (30, 34, 38)):
        m.fill(x0, top, x1, top + 1, '#')
    m.put(22, 41, 'U'); m.put(32, 37, 'g')
    # зиккурат: шесть ступеней по пять клеток вверх — без слабой тяжести на них не запрыгнуть
    for k in range(6):
        m.fill(38 + 6 * k, 46 - 5 * k, 112 - 6 * k, 58, '#')
    # на каждой ступени слева и справа — факел и защитник
    left = 'gkeko'
    right = 'ekgok'
    for k in range(5):
        y = 45 - 5 * k
        m.put(38 + 6 * k, y, 'L'); m.put(112 - 6 * k, y, 'L')
        m.put(41 + 6 * k, y, left[k]); m.put(109 - 6 * k, y, right[k])
    m.put(40, 45, '&')
    m.put(43, 45, 'H'); m.put(107, 45, 'U')
    m.put(49, 40, '4'); m.put(101, 40, 'N')
    m.put(55, 35, 'U'); m.put(95, 35, 'A')
    m.put(61, 30, 'H'); m.put(89, 30, 'U')
    m.put(67, 25, 'N'); m.put(83, 25, 'H')
    # вершина: храм с пультом, который открывает решётку у выхода
    m.put(75, 20, 'b'); m.put(70, 20, 'f'); m.put(80, 20, '&')
    m.put(68, 20, 'L'); m.put(82, 20, 'L')
    m.deco(70, 13, 71, 19, ','); m.deco(79, 13, 80, 19, ',')
    m.deco(69, 12, 81, 12, ',')
    # тайник в теле зиккурата: люк на третьей ступени
    floor_secret(m, 90, 31, 'MQ')
    # скраги кружат над лавой
    for (x, y) in ((27, 30), (50, 20), (100, 22), (110, 9), (122, 22)):
        m.put(x, y, 's')
    # от вершины — плиты к утёсу выхода
    for (x0, x1, top) in ((90, 94, 17), (102, 106, 14), (114, 118, 12), (124, 128, 16)):
        m.fill(x0, top, x1, top + 1, '#')
    m.put(92, 16, 'U'); m.put(104, 13, 'e'); m.put(116, 11, 'H'); m.put(126, 15, 'g')
    # утёс выхода: крыльцо, решётка, зал со слипгейтом
    m.fill(130, 20, 148, 58, '#')
    m.fill(135, 10, 148, 19, '#')
    m.fill(136, 14, 146, 19, ' ')
    m.fill(135, 16, 135, 19, '=')
    m.put(142, 19, 'E'); m.put(138, 15, 'L'); m.put(145, 15, 'L')
    m.put(132, 19, 'N')
    level({
        'id': 'e1m7', 'name': 'E1M7', 'title': 'Головокружение', 'theme': 'elder', 'episode': 1, 'secret': True,
        'next': 'e1m3', 'music': 41.2, 'gravity': 0.5,
        'hint': 'Здесь вдвое легче: прыжки выше и дальше',
        'kit': {'weapons': [1, 2, 3], 'ammo': {'shells': 50}, 'armor': 50},
    }, m)


