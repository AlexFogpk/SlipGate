def island(m, x0, x1, floor, depth=2, taper=True):
    """Парящий остров: верх на строке floor, снизу сужается к пустоте."""
    m.fill(x0, floor, x1, floor + depth - 1, '#')
    if taper and x1 - x0 >= 5:
        m.fill(x0 + 1, floor + depth, x1 - 1, floor + depth, '#')
        if x1 - x0 >= 9:
            m.fill(x0 + 3, floor + depth + 1, x1 - 3, floor + depth + 1, '#')


def puts(m, lst):
    for (x, y, c) in lst:
        m.put(x, y, c)


